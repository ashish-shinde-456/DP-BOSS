CREATE TABLE IF NOT EXISTS market_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market_name VARCHAR(255) NOT NULL,
    result_date DATE NOT NULL,
    open_pana VARCHAR(3),
    open_digit VARCHAR(1),
    close_pana VARCHAR(3),
    close_digit VARCHAR(1),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_market_results_market_date UNIQUE (market_name, result_date)
);

CREATE INDEX IF NOT EXISTS idx_market_results_latest
    ON market_results (result_date DESC, updated_at DESC);

CREATE TABLE IF NOT EXISTS scheduled_rajdhani_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market_name VARCHAR(32) NOT NULL,
    result_date DATE NOT NULL,
    open_pana VARCHAR(3) NOT NULL,
    open_digit VARCHAR(1) NOT NULL,
    close_pana VARCHAR(3),
    close_digit VARCHAR(1),
    open_publish_at TIMESTAMP WITH TIME ZONE NOT NULL,
    publish_at TIMESTAMP WITH TIME ZONE NOT NULL,
    open_published BOOLEAN NOT NULL DEFAULT FALSE,
    open_published_at TIMESTAMP WITH TIME ZONE,
    published BOOLEAN NOT NULL DEFAULT FALSE,
    published_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_rajdhani_result_market_date UNIQUE (market_name, result_date)
);

ALTER TABLE market_results
    ALTER COLUMN open_pana DROP NOT NULL,
    ALTER COLUMN open_digit DROP NOT NULL,
    ALTER COLUMN close_pana DROP NOT NULL,
    ALTER COLUMN close_digit DROP NOT NULL;

ALTER TABLE scheduled_rajdhani_results
    ADD COLUMN IF NOT EXISTS open_publish_at TIMESTAMP WITH TIME ZONE,
    ADD COLUMN IF NOT EXISTS open_published BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS open_published_at TIMESTAMP WITH TIME ZONE;

UPDATE scheduled_rajdhani_results
SET open_publish_at = CASE market_name
    WHEN 'RAJDHAN_DAY' THEN (result_date + TIME '15:15') AT TIME ZONE 'Asia/Kolkata'
    WHEN 'RAJDHAN_NIGHT' THEN (result_date + TIME '21:35') AT TIME ZONE 'Asia/Kolkata'
    ELSE publish_at
END
WHERE open_publish_at IS NULL;

UPDATE scheduled_rajdhani_results
SET open_published = TRUE,
    open_published_at = COALESCE(open_published_at, published_at, open_publish_at)
WHERE published = TRUE;

ALTER TABLE scheduled_rajdhani_results
    ALTER COLUMN close_pana DROP NOT NULL,
    ALTER COLUMN close_digit DROP NOT NULL,
    ALTER COLUMN open_publish_at SET NOT NULL;

CREATE INDEX IF NOT EXISTS idx_rajdhani_results_due
    ON scheduled_rajdhani_results (published, publish_at);

CREATE INDEX IF NOT EXISTS idx_rajdhani_results_open_due
    ON scheduled_rajdhani_results (open_published, open_publish_at);

CREATE TABLE IF NOT EXISTS golden_ank_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    result_date DATE NOT NULL,
    ank_one VARCHAR(1) NOT NULL,
    ank_two VARCHAR(1) NOT NULL,
    ank_three VARCHAR(1) NOT NULL,
    ank_four VARCHAR(1) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_golden_ank_results_date UNIQUE (result_date)
);

CREATE INDEX IF NOT EXISTS idx_golden_ank_results_effective_date
    ON golden_ank_results (result_date DESC);

CREATE TABLE IF NOT EXISTS admin_users (
    phone_number VARCHAR(10) PRIMARY KEY,
    display_name VARCHAR(80) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(16) NOT NULL CHECK (role IN ('OWNER', 'EDITOR')),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    password_changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_phone VARCHAR(10)
);

ALTER TABLE admin_users
    ADD COLUMN IF NOT EXISTS password_changed_at TIMESTAMP WITH TIME ZONE;

UPDATE admin_users
SET password_changed_at = created_at
WHERE password_changed_at IS NULL;

ALTER TABLE admin_users
    ALTER COLUMN password_changed_at SET DEFAULT CURRENT_TIMESTAMP;

ALTER TABLE admin_users
    ALTER COLUMN password_changed_at SET NOT NULL;

CREATE TABLE IF NOT EXISTS rajshree_market_timings (
    market_code VARCHAR(32) PRIMARY KEY
        CHECK (market_code IN ('RAJDHAN_DAY', 'RAJDHAN_NIGHT')),
    open_time TIME NOT NULL,
    close_time TIME NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by_phone VARCHAR(10) REFERENCES admin_users (phone_number)
);

CREATE TABLE IF NOT EXISTS admin_remember_tokens (
    token_id VARCHAR(36) PRIMARY KEY,
    phone_number VARCHAR(10) NOT NULL REFERENCES admin_users (phone_number) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_admin_remember_tokens_phone
    ON admin_remember_tokens (phone_number);

CREATE TABLE IF NOT EXISTS result_change_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_phone VARCHAR(10) NOT NULL,
    actor_name VARCHAR(80) NOT NULL,
    market_name VARCHAR(32) NOT NULL,
    result_date DATE NOT NULL,
    action VARCHAR(16) NOT NULL,
    previous_result VARCHAR(16),
    new_result VARCHAR(16) NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_result_change_audit_changed_at
    ON result_change_audit (changed_at DESC);
